#!/bin/sh
# Blocks Write/Edit on config/reference.php, which Symfony regenerates on cache warmup.
if grep -qE '"file_path"[[:space:]]*:[[:space:]]*"[^"]*config[/\\]+reference\.php"'; then
    echo "config/reference.php is generated by Symfony on cache warmup; don't edit it." >&2
    exit 2
fi
exit 0
